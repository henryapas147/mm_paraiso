SET NAMES utf8mb4;
SET @dbname = DATABASE();

CREATE TABLE IF NOT EXISTS user_roles (
    role_id         TINYINT(3)      NOT NULL AUTO_INCREMENT                   COMMENT 'PK',
    role_code       VARCHAR(30)     NOT NULL                                  COMMENT 'super_admin, admin, front_desk, housekeeping, canteen_staff, security, customer, api_client',
    role_label      VARCHAR(60)     NOT NULL,
    permissions     JSON            NULL                                      COMMENT 'JSON array of permission keys',
    is_system_role  TINYINT(1)      NOT NULL DEFAULT 1                        COMMENT '1 = built-in, cannot be deleted',
    is_active       TINYINT(1)      NOT NULL DEFAULT 1,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id),
    UNIQUE KEY uk_role_code (role_code),
    KEY idx_is_active (is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='System roles with JSON permission definitions';

CREATE TABLE IF NOT EXISTS user_accounts (
    user_id                 CHAR(36)        NOT NULL                          COMMENT 'PK – UUID v4, generated by app',
    role_id                 TINYINT(3)      NOT NULL                          COMMENT 'FK → user_roles.role_id',
    email                   VARCHAR(180)    NOT NULL,
    phone_number            VARCHAR(20)     NULL,
    password_hash           VARCHAR(255)    NOT NULL                          COMMENT 'bcrypt/argon2id — NEVER store plaintext',
    password_changed_at     TIMESTAMP       NULL,
    account_status          ENUM('active','inactive','suspended','pending_verification')
                                            NOT NULL DEFAULT 'pending_verification',
    is_email_verified       TINYINT(1)      NOT NULL DEFAULT 0,
    is_phone_verified       TINYINT(1)      NOT NULL DEFAULT 0,
    email_verified_at       TIMESTAMP       NULL,
    phone_verified_at       TIMESTAMP       NULL,
    email_verify_token      VARCHAR(100)    NULL,
    email_verify_expiry     TIMESTAMP       NULL,
    password_reset_token    VARCHAR(100)    NULL,
    password_reset_expiry   TIMESTAMP       NULL,
    google_id               VARCHAR(255)    NULL,
    failed_login_count      TINYINT(3)      NOT NULL DEFAULT 0                COMMENT 'Reset on successful login',
    locked_until            TIMESTAMP       NULL                              COMMENT 'Locked after too many failed attempts',
    last_login_at           TIMESTAMP       NULL,
    last_login_ip           VARCHAR(45)     NULL,
    created_by              CHAR(36)        NULL,
    updated_by              CHAR(36)        NULL,
    created_at              TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at              TIMESTAMP       NULL                              COMMENT 'Soft delete — NULL = not deleted',
    PRIMARY KEY (user_id),
    UNIQUE KEY uk_email (email),
    UNIQUE KEY uk_phone_number (phone_number),
    KEY idx_role_id (role_id),
    KEY idx_account_status (account_status),
    KEY idx_deleted_at (deleted_at),
    CONSTRAINT fk_ua_role_id FOREIGN KEY (role_id) REFERENCES user_roles(role_id) ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Core credentials — UUID PK, soft delete, brute-force lockout support';

CREATE TABLE IF NOT EXISTS user_profiles (
    profile_id                  CHAR(36)        NOT NULL                      COMMENT 'PK – UUID v4',
    user_id                     CHAR(36)        NOT NULL                      COMMENT 'FK → user_accounts.user_id',
    first_name                  VARCHAR(80)     NOT NULL,
    last_name                   VARCHAR(80)     NOT NULL,
    middle_name                 VARCHAR(80)     NULL,
    display_name                VARCHAR(120)    NULL,
    date_of_birth               DATE            NULL,
    gender                      ENUM('male','female','other','prefer_not_to_say') NULL,
    nationality                 VARCHAR(60)     NULL                          DEFAULT 'Filipino',
    id_type                     ENUM('passport','drivers_license','national_id','philsys_id','sss','pagibig','voters_id','postal_id','other') NULL,
    id_number                   VARCHAR(80)     NULL                          COMMENT 'Encrypt at application level',
    id_expiry_date              DATE            NULL,
    id_image_url                VARCHAR(500)    NULL,
    id_verified                 TINYINT(1)      NOT NULL DEFAULT 0,
    id_verified_by              CHAR(36)        NULL                          COMMENT 'FK → user_accounts.user_id (staff who verified)',
    id_verified_at              TIMESTAMP       NULL,
    profile_photo_url           VARCHAR(500)    NULL,
    address_line1               VARCHAR(255)    NULL,
    address_line2               VARCHAR(255)    NULL,
    city                        VARCHAR(80)     NULL,
    province                    VARCHAR(80)     NULL,
    postal_code                 VARCHAR(20)     NULL,
    country                     VARCHAR(60)     NOT NULL DEFAULT 'Philippines',
    emergency_contact_name      VARCHAR(120)    NULL,
    emergency_contact_phone     VARCHAR(20)     NULL,
    emergency_contact_relation  VARCHAR(50)     NULL,
    preferred_language          VARCHAR(10)     NOT NULL DEFAULT 'en',
    marketing_opt_in            TINYINT(1)      NOT NULL DEFAULT 0,
    notes                       TEXT            NULL                          COMMENT 'Internal staff notes',
    created_at                  TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (profile_id),
    UNIQUE KEY uk_user_id (user_id),
    KEY idx_full_name (last_name, first_name),
    CONSTRAINT fk_up_user_id FOREIGN KEY (user_id) REFERENCES user_accounts(user_id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Extended guest/staff profile — PII separated from auth';

CREATE TABLE IF NOT EXISTS user_sessions (
    session_id          CHAR(36)        NOT NULL                              COMMENT 'PK – UUID v4',
    user_id             CHAR(36)        NOT NULL                              COMMENT 'FK → user_accounts.user_id',
    token_hash          VARCHAR(255)    NOT NULL                              COMMENT 'SHA-256 of JWT — never store raw token',
    refresh_token_hash  VARCHAR(255)    NULL,
    device_type         ENUM('web','mobile_ios','mobile_android','desktop','api','other') NOT NULL DEFAULT 'web',
    device_name         VARCHAR(120)    NULL,
    user_agent          TEXT            NULL,
    ip_address          VARCHAR(45)     NULL,
    is_active           TINYINT(1)      NOT NULL DEFAULT 1,
    expires_at          TIMESTAMP       NOT NULL,
    last_active_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (session_id),
    UNIQUE KEY uk_token_hash (token_hash),
    KEY idx_user_id (user_id),
    KEY idx_user_active (user_id, is_active),
    KEY idx_expires_at (expires_at),
    CONSTRAINT fk_us_user_id FOREIGN KEY (user_id) REFERENCES user_accounts(user_id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Active sessions per device — supports multi-device and admin force-logout';

CREATE TABLE IF NOT EXISTS audit_logs (
    log_id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT                   COMMENT 'PK – BIGINT for high volume',
    user_id         CHAR(36)        NULL                                      COMMENT 'FK → user_accounts.user_id (NULL = system)',
    action          VARCHAR(80)     NOT NULL                                  COMMENT 'e.g. user.login, reservation.created, payment.processed',
    entity_type     VARCHAR(60)     NULL                                      COMMENT 'Affected table name',
    entity_id       VARCHAR(36)     NULL                                      COMMENT 'PK of affected row',
    old_values      JSON            NULL,
    new_values      JSON            NULL,
    ip_address      VARCHAR(45)     NULL,
    user_agent      TEXT            NULL,
    status          ENUM('success','failure','error') NOT NULL DEFAULT 'success',
    error_message   TEXT            NULL,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (log_id),
    KEY idx_user_id (user_id),
    KEY idx_action (action),
    KEY idx_entity (entity_type, entity_id),
    KEY idx_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Immutable audit trail — DO NOT update or delete rows';

CREATE TABLE IF NOT EXISTS login_attempts (
    attempt_id     BIGINT UNSIGNED NOT NULL AUTO_INCREMENT                   COMMENT 'PK – BIGINT for high volume',
    email          VARCHAR(180)    NOT NULL,
    ip_address     VARCHAR(45)     NOT NULL,
    user_agent     TEXT            NULL,
    status         ENUM('success','failed','blocked') NOT NULL DEFAULT 'failed',
    created_at     TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (attempt_id),
    KEY idx_email (email),
    KEY idx_ip_address (ip_address),
    KEY idx_created_at (created_at),
    KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Login attempt tracking for rate limiting and security monitoring';

